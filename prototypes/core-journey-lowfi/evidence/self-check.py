"""Operate the connected low-fi in real Chrome. No microphone or backend proof."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

root=Path(__file__).parent
checks=[]
def passed(name): checks.append({'scenario':name,'result':'PASS'})
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:5178')
    page.locator('.lab summary').click()
    page.get_by_role('button',name='Restart journey').click()
    page.locator('.lab summary').click()
    page.wait_for_function('document.querySelector("#scene").readyState >= 3')
    expect(page.locator('#next')).to_be_disabled()
    expect(page.locator('#take')).to_be_disabled()
    passed('Initial empty turn cannot advance; no autoplay')
    page.locator('#replay').click()
    page.wait_for_function('document.querySelector("#scene").currentTime > 1')
    page.wait_for_function('document.querySelector("#scene").paused && document.querySelector("#scene").currentTime >= 5',timeout=10000)
    page.locator('#replay').click()
    page.wait_for_function('!document.querySelector("#scene").paused && document.querySelector("#scene").currentTime < 1')
    passed('Replay from fixed-window end restarts and plays')
    page.locator('#record').click()
    expect(page.locator('#capture-badge')).to_be_visible()
    expect(page.locator('#next')).to_be_disabled()
    expect(page.locator('#scrub')).to_be_disabled()
    expect(page.locator('#previous')).to_be_disabled()
    page.wait_for_function('!document.querySelector("#take").disabled',timeout=10000)
    passed('Record supersedes playback; fixed-window automatic stop; controls locked')
    first=page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).candidates[0].id')
    page.locator('#take').click()
    page.wait_for_function('!document.querySelector("#take-audio").paused && !document.querySelector("#scene").paused')
    expect(page.locator('#scene')).to_have_js_property('muted',True)
    passed('Your take plays synthetic candidate audio with synchronized muted source video')
    page.locator('#record').click()
    page.wait_for_function('!document.querySelector("#take").disabled',timeout=10000)
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).candidates[0].id')!=first
    passed('Rerecord replaces candidate only after new capture completes')
    page.screenshot(path=str(root/'desktop-record.png'),full_page=True)
    page.locator('#next').click()
    expect(page.locator('#position')).to_have_text('Line 2 of 3')
    expect(page.locator('#process-again')).to_be_disabled()
    page.locator('#record').click()
    page.wait_for_function('!document.querySelector("#take").disabled',timeout=10000)
    candidate=page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).candidates[1].id')
    page.locator('.lab summary').click()
    page.locator('#fail-save').check()
    page.locator('.lab summary').click()
    page.locator('#next').click()
    expect(page.locator('#feedback')).to_contain_text('Couldn’t save')
    expect(page.locator('#position')).to_have_text('Line 2 of 3')
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).candidates[1].id')==candidate
    page.screenshot(path=str(root/'failed-save.png'),full_page=True)
    page.locator('#take').click()
    page.wait_for_function('!document.querySelector("#take-audio").paused')
    page.locator('#pause').click()
    passed('Failed save retains exact candidate on same line and remains auditionable')
    page.reload()
    expect(page.locator('#position')).to_have_text('Line 2 of 3')
    expect(page.locator('#take')).to_be_enabled()
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).candidates[1].id')==candidate
    passed('Browser-local draft survives reload (not account storage proof)')
    page.locator('#next').click()
    expect(page.locator('#position')).to_have_text('Line 3 of 3')
    page.locator('#previous').click()
    expect(page.locator('#saved')).to_have_text('Saved')
    page.locator('#next').click()
    expect(page.locator('#position')).to_have_text('Line 3 of 3')
    passed('Retry acceptance and accepted revisit use sequential navigation')
    page.locator('#record').click()
    page.wait_for_function('!document.querySelector("#take").disabled',timeout=10000)
    page.locator('#previous').click()
    expect(page.locator('#guard')).to_be_visible()
    page.get_by_role('button',name='Stay',exact=True).click()
    expect(page.locator('#position')).to_have_text('Line 3 of 3')
    expect(page.locator('#take')).to_be_enabled()
    page.locator('#next').click()
    expect(page.locator('#assembly')).to_be_visible()
    expect(page.locator('#result')).to_be_visible(timeout=5000)
    page.screenshot(path=str(root/'desktop-result.png'),full_page=True)
    page.locator('#result').evaluate('(v)=>v.play()')
    page.wait_for_function('document.querySelector("#result").currentTime > .4')
    with page.expect_download() as download:
        page.locator('#download').click()
    assert download.value.suggested_filename.endswith('.mp4')
    passed('Final durable simulated acceptance leads assembly → playable distinct output fixture → download')
    page.locator('#return').click()
    expect(page.locator('#position')).to_have_text('Line 1 of 3')
    assert page.locator('#result').evaluate('(v)=>v.paused')
    passed('Return opens first saved line, no capture, and stops result playback')
    accepted=page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).accepted[0].id')
    page.locator('.lab summary').click()
    page.locator('#fail-mic').check()
    page.locator('.lab summary').click()
    page.locator('#record').click()
    expect(page.locator('#feedback')).to_contain_text('Microphone access is unavailable')
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).accepted[0].id')==accepted
    page.get_by_role('button',name='Open Settings').click()
    expect(page.locator('#settings-note')).to_be_visible()
    page.locator('#destination-close').click()
    passed('Blocked capture preserves accepted take; recovery links only to Settings boundary')
    page.locator('#record').click()
    page.wait_for_function('!document.querySelector("#take").disabled',timeout=10000)
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).accepted[0].id')==accepted
    page.get_by_role('button',name='Settings',exact=True).click()
    page.get_by_role('button',name='Leave without saving',exact=True).click()
    expect(page.locator('#destination')).to_be_visible()
    page.locator('#destination-close').click()
    assert page.evaluate('JSON.parse(localStorage.getItem("dubbed-lowfi-v1")).accepted[0].id')==accepted
    passed('Leaving without candidate preserves prior accepted media')
    for width,height,name in [(1440,900,'desktop-ready'),(1280,600,'short-desktop'),(390,844,'phone-record'),(390,667,'short-phone')]:
        page.set_viewport_size({'width':width,'height':height})
        page.screenshot(path=str(root/f'{name}.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        if width<768:
            for selector in ['#record','#replay','#take','#next','#previous']:
                assert page.locator(selector).bounding_box()['height']>=48
        passed(f'{width}×{height}: no horizontal overflow; visible full-image stage; reachable controls')
    page.locator('.lab summary').click()
    page.locator('#long-line').check()
    page.locator('.lab summary').click()
    page.screenshot(path=str(root/'phone-long-dialogue.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    passed('Long Russian dialogue wraps on short phone without horizontal overflow')
    page.keyboard.press('Tab')
    assert page.evaluate('document.activeElement !== document.body')
    passed('Keyboard focus reaches native interactive control')
    assert not errors,errors
    (root/'self-check-results.json').write_text(json.dumps({'browser':browser.version,'date':'2026-10-27','environment':'Windows, real Chrome headless, DPR 1; mouse/keyboard automation, no real mic/backend/mobile hardware','checks':checks,'pageErrors':errors},indent=2),encoding='utf8')
    browser.close()
print(json.dumps(checks,indent=2))
